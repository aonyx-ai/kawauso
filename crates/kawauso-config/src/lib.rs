//! Configuration files for Kawauso applications
//!
//! This crate loads the configuration files of Kawauso tools, so that every
//! tool finds, loads, and deserializes its configuration in the same way and
//! reports failures with the same clear errors. The specification in
//! `SPECIFICATION.md` defines the requirements of the crate, and ADR-004
//! records why the crate exists.
